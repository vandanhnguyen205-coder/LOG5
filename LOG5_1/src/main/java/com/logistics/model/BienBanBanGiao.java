package com.logistics.model;

public class BienBanBanGiao {
    private String maBienBan;
    private String maDon;
    private String maTaiXe;
    private String maKiemDuyetVien;
    private String nguoiNhan;
    private String tinhTrangHang;
    private double nhietDoLucGiao;
    private String thoiDiemGiao;
    private String ketQua;

    public BienBanBanGiao() {}

    public String getMaBienBan() { return maBienBan; }
    public void setMaBienBan(String maBienBan) { this.maBienBan = maBienBan; }

    public String getMaDon() { return maDon; }
    public void setMaDon(String maDon) { this.maDon = maDon; }

    public String getMaTaiXe() { return maTaiXe; }
    public void setMaTaiXe(String maTaiXe) { this.maTaiXe = maTaiXe; }

    public String getMaKiemDuyetVien() { return maKiemDuyetVien; }
    public void setMaKiemDuyetVien(String maKiemDuyetVien) { this.maKiemDuyetVien = maKiemDuyetVien; }

    public String getNguoiNhan() { return nguoiNhan; }
    public void setNguoiNhan(String nguoiNhan) { this.nguoiNhan = nguoiNhan; }

    public String getTinhTrangHang() { return tinhTrangHang; }
    public void setTinhTrangHang(String tinhTrangHang) { this.tinhTrangHang = tinhTrangHang; }

    public double getNhietDoLucGiao() { return nhietDoLucGiao; }
    public void setNhietDoLucGiao(double nhietDoLucGiao) { this.nhietDoLucGiao = nhietDoLucGiao; }

    public String getThoiDiemGiao() { return thoiDiemGiao; }
    public void setThoiDiemGiao(String thoiDiemGiao) { this.thoiDiemGiao = thoiDiemGiao; }

    public String getKetQua() { return ketQua; }
    public void setKetQua(String ketQua) { this.ketQua = ketQua; }
}