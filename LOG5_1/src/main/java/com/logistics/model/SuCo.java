package com.logistics.model;

public class SuCo {
    private String maSuCo;
    private String maDon;
    private String maTaiXe;
    private String maDieuPhoiVien;
    private String loaiSuCo;
    private String moTa;
    private String thoiDiem;
    private String hinhAnh;
    private String phuongAnXuLy;
    private String trangThai;

    public SuCo() {}

    public String getMaSuCo() { return maSuCo; }
    public void setMaSuCo(String maSuCo) { this.maSuCo = maSuCo; }

    public String getMaDon() { return maDon; }
    public void setMaDon(String maDon) { this.maDon = maDon; }

    public String getMaTaiXe() { return maTaiXe; }
    public void setMaTaiXe(String maTaiXe) { this.maTaiXe = maTaiXe; }

    public String getMaDieuPhoiVien() { return maDieuPhoiVien; }
    public void setMaDieuPhoiVien(String maDieuPhoiVien) { this.maDieuPhoiVien = maDieuPhoiVien; }

    public String getLoaiSuCo() { return loaiSuCo; }
    public void setLoaiSuCo(String loaiSuCo) { this.loaiSuCo = loaiSuCo; }

    public String getMoTa() { return moTa; }
    public void setMoTa(String moTa) { this.moTa = moTa; }

    public String getThoiDiem() { return thoiDiem; }
    public void setThoiDiem(String thoiDiem) { this.thoiDiem = thoiDiem; }

    public String getHinhAnh() { return hinhAnh; }
    public void setHinhAnh(String hinhAnh) { this.hinhAnh = hinhAnh; }

    public String getPhuongAnXuLy() { return phuongAnXuLy; }
    public void setPhuongAnXuLy(String phuongAnXuLy) { this.phuongAnXuLy = phuongAnXuLy; }

    public String getTrangThai() { return trangThai; }
    public void setTrangThai(String trangThai) { this.trangThai = trangThai; }
}