package com.logistics.model;

public class PhanCong {
    private String maPhanCong;
    private String maDon;
    private String maDieuPhoiVien;
    private String maTaiXe;
    private String maPhuongTien;
    private String tuyenDuong;
    private String thoiGianDuKien;
    private String trangThai;

    public PhanCong() {}

    public String getMaPhanCong() { return maPhanCong; }
    public void setMaPhanCong(String maPhanCong) { this.maPhanCong = maPhanCong; }

    public String getMaDon() { return maDon; }
    public void setMaDon(String maDon) { this.maDon = maDon; }

    public String getMaDieuPhoiVien() { return maDieuPhoiVien; }
    public void setMaDieuPhoiVien(String maDieuPhoiVien) { this.maDieuPhoiVien = maDieuPhoiVien; }

    public String getMaTaiXe() { return maTaiXe; }
    public void setMaTaiXe(String maTaiXe) { this.maTaiXe = maTaiXe; }

    public String getMaPhuongTien() { return maPhuongTien; }
    public void setMaPhuongTien(String maPhuongTien) { this.maPhuongTien = maPhuongTien; }

    public String getTuyenDuong() { return tuyenDuong; }
    public void setTuyenDuong(String tuyenDuong) { this.tuyenDuong = tuyenDuong; }

    public String getThoiGianDuKien() { return thoiGianDuKien; }
    public void setThoiGianDuKien(String thoiGianDuKien) { this.thoiGianDuKien = thoiGianDuKien; }

    public String getTrangThai() { return trangThai; }
    public void setTrangThai(String trangThai) { this.trangThai = trangThai; }
}